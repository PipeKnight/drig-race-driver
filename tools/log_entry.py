"""Project log entries in log/: create, check and renumber them, regenerate the indexes.

Each entry is one file, log/F0532.md, whose first line is
"F532 Title (2026-10-21, author; request)" followed by bullets. Graphics entries use the
G series (log/G0129.md). Python standard library only; run with `py -I` from the repository:

    py -I tools/log_entry.py new "Title" [--author "Claude Code, session"] [--request "..."]
    py -I tools/log_entry.py check [--fix]
    py -I tools/log_entry.py index

Push flow (docs: AGENTS.md "Durable records"):
  1. `new "Title"` creates the next free number (highest on freshly fetched origin/main or
     in log/, plus one) and prints the path; write the bullets there and commit it with the
     work, squashed into one commit.
  2. `git fetch origin && git rebase origin/main`. If the rebase stops on log/ files,
     log/INDEX.md or PROJECT_LOG.md: `check --fix`, then `git rebase --continue`; repeat.
  3. `check --fix`: renumbers an entry whose number another session took meanwhile
     (file name, the number inside the entry, the indexes) and regenerates log/INDEX.md and
     the index table in PROJECT_LOG.md. Commit what it changed (`git commit --amend`).
  4. `check` must pass; push. A rejected push means origin moved: go back to step 2.

check fails when two files carry the same number, when an entry's number on origin/main
holds a different entry (another session's), when a change removes text from an entry that
is already on origin/main (use --allow-edit N for a deliberate correction), when an entry
still has the placeholder bullet, or when an index is stale. --fix repairs the first and the
last automatically; it never pushes, commits or continues a rebase.
"""

import argparse
import datetime
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "log"
STATE = ROOT / "PROJECT_LOG.md"
INDEX = LOG / "INDEX.md"
BASE = "origin/main"
PLACEHOLDER = "- (write the bullets here)"
NAME = re.compile(r"^([FG])(\d+)(.*)\.md$")
STATE_START = "<!-- log-index:start (generated by tools/log_entry.py; do not edit by hand) -->"
STATE_END = "<!-- log-index:end -->"
STATE_ROWS = 60
MONTHS = {m: i for i, m in enumerate(
    "January February March April May June July August September October November December".split(), 1)}


# --- git helpers -------------------------------------------------------------------------

def git(*args, check=True, input=None):
    r = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, input=input,
                       encoding="utf-8", errors="replace")
    if check and r.returncode:
        raise SystemExit("git %s failed: %s" % (" ".join(args), r.stderr.strip()))
    return r.stdout


def has_ref(ref):
    return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--verify", "-q", ref],
                          capture_output=True).returncode == 0


def fetch(no_fetch):
    if no_fetch:
        return
    r = subprocess.run(["git", "-C", str(ROOT), "fetch", "-q", "origin"], capture_output=True, text=True)
    if r.returncode:
        print("warning: git fetch failed, using the last fetched %s: %s" % (BASE, r.stderr.strip()))


def show(ref_path):
    r = subprocess.run(["git", "-C", str(ROOT), "show", ref_path], capture_output=True)
    return r.stdout.decode("utf-8").replace("\r\n", "\n") if r.returncode == 0 else None


def base_tree(base):
    """{relative path under log/: blob id} on the base ref."""
    if not has_ref(base):
        return {}
    out = {}
    for line in git("ls-tree", "-r", base, "--", "log/").splitlines():
        meta, path = line.split("\t", 1)
        out[path[len("log/"):]] = meta.split()[2]
    return out


def local_blobs(paths):
    """Blob ids of working-tree files as git would store them (line-ending filters applied)."""
    if not paths:
        return {}
    rel = [p.relative_to(ROOT).as_posix() for p in paths]
    ids = git("hash-object", "--stdin-paths", input="\n".join(rel) + "\n").split()
    return dict(zip(paths, ids))


def max_in_old_state(base):
    """Highest F number at a line start of the base PROJECT_LOG.md (the pre-log/ format)."""
    text = show("%s:PROJECT_LOG.md" % base) or ""
    nums = [int(m.group(1)) for m in re.finditer(r"^F(\d+)", text, re.M)]
    return max(nums, default=0)


# --- entries -----------------------------------------------------------------------------

def read(path):
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def write(path, text):
    path.write_bytes(text.encode("utf-8"))


def entry_files():
    """[(series, number, path)] for log/F*.md and log/G*.md, including odd names."""
    out = []
    for p in sorted(LOG.glob("*.md")):
        m = NAME.match(p.name)
        if m:
            out.append((m.group(1), int(m.group(2)), p))
    return out


def canonical(series, number):
    return "%s%04d.md" % (series, number)


def highest(series, base):
    nums = [n for s, n, _ in entry_files() if s == series]
    for path in base_tree(base):
        m = NAME.match(path)
        if m and m.group(1) == series:
            nums.append(int(m.group(2)))
    if series == "F" and has_ref(base):
        nums.append(max_in_old_state(base))
    return max(nums, default=0)


def header_line(text, series, number):
    """The line that names the entry: its first line, or a legacy `### ... (F103)` heading."""
    pat = re.compile(r"(?<![A-Za-z0-9])%s0*%d(?!\d)" % (series, number))
    for line in text.split("\n")[:3]:
        if pat.search(line):
            return line
    return None


def parse_header(line, series, number):
    """(date, title) from an entry header line."""
    h = re.sub(r"^#+\s*", "", line)
    h = re.sub(r"^%s0*%d\b[\s:\u2014-]*" % (series, number), "", h)
    date, cut = "", None
    m = re.search(r"\(([^()]*?)\b(\d{4}-\d{2}-\d{2})\b", h)
    if m:
        date, cut = m.group(2), m.start()
    else:
        m = re.search(r"\(?(\d{1,2}) ?(%s) ?(\d{4})" % "|".join(MONTHS), h)
        if m:
            date = "%s-%02d-%02d" % (m.group(3), MONTHS[m.group(2)], int(m.group(1)))
            cut = m.start()
    title = h[:cut] if cut else h
    title = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", title).replace("**", "").replace("`", "")
    title = title.strip().rstrip(":;,.\u2014- ").strip()
    if not cut and len(title) > 110:
        title = title[:110].rsplit(" ", 1)[0] + " \u2026"
    elif len(title) > 160:
        title = title[:160].rsplit(" ", 1)[0] + " \u2026"
    return date, title.replace("|", "\\|")


def entries_for_index():
    rows = []
    for s, n, p in entry_files():
        text = read(p)
        line = header_line(text, s, n) or text.split("\n", 1)[0]
        date, title = parse_header(line, s, n)
        rows.append((s, n, p.name, date, title))
    return rows


# --- indexes -----------------------------------------------------------------------------

def render_index(rows):
    out = [
        "# Log index",
        "",
        "Generated by `py -I tools/log_entry.py index` (also by `check --fix`); do not edit by hand.",
        "One line per entry, newest first. The current state is in [PROJECT_LOG.md](../PROJECT_LOG.md);",
        "details are in the entry files: `grep -rn \"F512 \" log/` lands in log/F0512.md.",
        "",
        "## F entries",
        "",
        "| Entry | Date | Title |",
        "|---|---|---|",
    ]
    for s, n, name, date, title in sorted((r for r in rows if r[0] == "F"), key=lambda r: -r[1]):
        out.append("| [F%d](%s) | %s | %s |" % (n, name, date, title))
    out += ["", "## G entries (graphics, Codex)", "", "| Entry | Date | Title |", "|---|---|---|"]
    for s, n, name, date, title in sorted((r for r in rows if r[0] == "G"), key=lambda r: -r[1]):
        out.append("| [G%03d](%s) | %s | %s |" % (n, name, date, title))
    out += ["", "## Legacy sections (6\u20139 October 2026 layout)", "",
            "F001\u2013F095 are rows of the table in [legacy/002](legacy/002-confirmed-findings.md); "
            "F096\u2013F102 are named inside the 7 and 8 October sessions below "
            "(`grep -rn \"F097\" log/legacy/`). F103\u2013F138 have their own files above.", ""]
    for p in sorted((LOG / "legacy").glob("*.md")):
        first = next((l for l in read(p).split("\n") if l.startswith("###")), read(p).split("\n", 1)[0])
        out.append("- [%s](legacy/%s) %s" % (p.stem[:3], p.name, first.lstrip("# ").replace("|", "\\|")))
    return "\n".join(out) + "\n"


def render_state_block(rows):
    out = [STATE_START, "", "| Entry | Date | Title |", "|---|---|---|"]
    recent = sorted((r for r in rows if r[0] == "F"), key=lambda r: -r[1])[:STATE_ROWS]
    for s, n, name, date, title in recent:
        out.append("| [F%d](log/%s) | %s | %s |" % (n, name, date, title))
    out += ["", "Older entries: [log/INDEX.md](log/INDEX.md).", "", STATE_END]
    return "\n".join(out)


def with_state_block(state_text, block):
    a, b = state_text.find(STATE_START), state_text.find(STATE_END)
    if a < 0 or b < 0:
        raise SystemExit("PROJECT_LOG.md lacks the %s ... %s markers" % (STATE_START, STATE_END))
    return state_text[:a] + block + state_text[b + len(STATE_END):]


def strip_state_block(state_text):
    """The state text with an empty generated block, for comparing the hand-written part."""
    a, b = state_text.find(STATE_START), state_text.find(STATE_END)
    if a < 0 or b < 0:
        return state_text
    return state_text[:a] + STATE_START + "\n" + STATE_END + state_text[b + len(STATE_END):]


def stale_indexes():
    rows = entries_for_index()
    want_index = render_index(rows)
    want_state = with_state_block(read(STATE), render_state_block(rows))
    stale = []
    if not INDEX.exists() or read(INDEX) != want_index:
        stale.append((INDEX, want_index))
    if read(STATE) != want_state:
        stale.append((STATE, want_state))
    return stale


def regenerate():
    changed = []
    for path, text in stale_indexes():
        write(path, text)
        changed.append(path)
    return changed


# --- renumbering -------------------------------------------------------------------------

def renumber_text(text, series, old, new):
    return re.sub(r"(?<![A-Za-z0-9])%s0*%d(?!\d)" % (series, old), "%s%d" % (series, new), text)


class Numbers:
    """Hands out free numbers above everything local and on the base."""

    def __init__(self, base):
        self.next = {s: highest(s, base) + 1 for s in "FG"}

    def take(self, series):
        n = self.next[series]
        self.next[series] += 1
        return n


def move_entry(text, series, old, numbers, changed_files):
    new = numbers.take(series)
    path = LOG / canonical(series, new)
    write(path, renumber_text(text, series, old, new))
    print("renumbered %s%d -> %s%d: %s" % (series, old, series, new, path.relative_to(ROOT).as_posix()))
    for f in changed_files:
        p = ROOT / f
        other = strip_state_block(read(p)) if p == STATE else read(p) if p.is_file() else ""
        if not f.startswith("log/") and re.search(r"(?<![A-Za-z0-9])%s%d(?!\d)" % (series, old), other):
            print("  note: %s mentions %s%d; if it means this entry, change it to %s%d" % (
                f, series, old, series, new))
    return path


# --- conflicts during a rebase or merge ----------------------------------------------------

def unmerged():
    """{path: {stage: blob}} for unmerged index entries."""
    out = {}
    for line in git("ls-files", "-u").splitlines():
        meta, path = line.split("\t", 1)
        _, blob, stage = meta.split()
        out.setdefault(path, {})[int(stage)] = blob
    return out


def blob_text(blob):
    return git("cat-file", "blob", blob).replace("\r\n", "\n")


def in_rebase():
    gd = Path(git("rev-parse", "--git-dir").strip())
    gd = gd if gd.is_absolute() else ROOT / gd
    return (gd / "rebase-merge").exists() or (gd / "rebase-apply").exists()


def in_merge():
    gd = Path(git("rev-parse", "--git-dir").strip())
    gd = gd if gd.is_absolute() else ROOT / gd
    return in_rebase() or (gd / "MERGE_HEAD").exists()


def resolve_conflicts(base, fix, numbers, changed_files):
    """Resolve log/ and index conflicts; return the problems left."""
    problems = []
    conflicts = unmerged()
    if not conflicts:
        return problems
    upstream_stage = 2 if in_rebase() else 3
    base_blobs = base_tree(base)
    generated = False
    for path, stages in sorted(conflicts.items()):
        m = NAME.match(path[len("log/"):]) if path.startswith("log/") and path.count("/") == 1 else None
        if path in ("log/INDEX.md", "PROJECT_LOG.md"):
            generated = True
            continue
        if not m:
            problems.append("unmerged %s: resolve it by hand" % path)
            continue
        if 2 not in stages or 3 not in stages:
            problems.append("unmerged %s (added or deleted on one side only): resolve it by hand" % path)
            continue
        if not fix:
            problems.append("unmerged %s: both sides wrote entry %s; run check --fix" % (path, path[4:-3]))
            continue
        on_base = base_blobs.get(path[len("log/"):])
        up = 3 if stages[3] == on_base and stages[2] != on_base else (
            2 if stages[2] == on_base else upstream_stage)
        mine = 5 - up
        up_text, my_text = blob_text(stages[up]), blob_text(stages[mine])
        write(ROOT / path, up_text)
        git("add", "--", path)
        if my_text != up_text:
            new = move_entry(my_text, m.group(1), int(m.group(2)), numbers, changed_files)
            git("add", "--", new.relative_to(ROOT).as_posix())
    if generated:
        if "PROJECT_LOG.md" in conflicts:
            st = conflicts["PROJECT_LOG.md"]
            parts = {k: strip_state_block(blob_text(v)) for k, v in st.items()}
            o, a, b = parts.get(1), parts.get(2), parts.get(3)
            if a == b or b == o:
                merged = a
            elif a == o:
                merged = b
            else:
                merged = None
            if merged is None or not fix:
                problems.append("unmerged PROJECT_LOG.md: the state text outside the generated index differs "
                                "on both sides; merge it by hand, keep the log-index markers, then rerun check --fix"
                                if merged is None else "unmerged PROJECT_LOG.md: run check --fix")
            elif STATE_START not in merged or STATE_END not in merged:
                problems.append("PROJECT_LOG.md lost its log-index markers; restore them by hand")
            else:
                write(STATE, merged)
        if fix and not problems:
            if not (ROOT / "log/INDEX.md").exists() or "log/INDEX.md" in conflicts:
                write(INDEX, "")
            regenerate()
            for p in ("log/INDEX.md", "PROJECT_LOG.md"):
                if p in conflicts:
                    git("add", "--", p)
        elif not fix:
            problems.append("unmerged generated files (log/INDEX.md / PROJECT_LOG.md): run check --fix")
    if fix and not problems:
        print("conflicts resolved and staged")
    return problems


# --- commands ----------------------------------------------------------------------------

def cmd_new(a):
    fetch(a.no_fetch)
    n = a.number or highest(a.series, a.base) + 1
    path = LOG / canonical(a.series, n)
    if path.exists():
        raise SystemExit("%s already exists" % path.relative_to(ROOT).as_posix())
    date = a.date or datetime.date.today().isoformat()
    who = a.author + ("; " + a.request if a.request else "")
    write(path, "%s%d %s (%s, %s).\n%s\n" % (a.series, n, a.title.strip(), date, who, PLACEHOLDER))
    print(path.relative_to(ROOT).as_posix())
    return 0


def cmd_index(a):
    changed = regenerate()
    print("regenerated: %s" % (", ".join(p.relative_to(ROOT).as_posix() for p in changed) or "nothing changed"))
    return 0


def cmd_check(a):
    fetch(a.no_fetch)
    base = a.base
    problems, notes = [], []
    changed_files = [f for f in git("diff", "--name-only", base, check=False).splitlines()] if has_ref(base) else []
    numbers = Numbers(base)
    problems += resolve_conflicts(base, a.fix, numbers, changed_files)
    if not problems and in_merge():
        if a.fix:
            for p in regenerate():
                git("add", "--", p.relative_to(ROOT).as_posix())
        problems.append("a rebase or merge is in progress: `git rebase --continue` (or commit the merge), "
                        "then run check again")
    if problems:
        for p in problems:
            print("FAIL:", p)
        return 1
    files = entry_files()
    # Names: canonical, one file per number, number named in the header.
    by_key = {}
    for s, n, p in files:
        by_key.setdefault((s, n), []).append(p)
    for (s, n), paths in sorted(by_key.items()):
        for p in paths:
            if p.name != canonical(s, n) or len(paths) > 1:
                if len(paths) > 1 and p.name == canonical(s, n):
                    continue
                if a.fix:
                    text = read(p)
                    p.unlink()
                    target = LOG / canonical(s, n)
                    if target.exists():
                        move_entry(text, s, n, numbers, changed_files)
                    else:
                        write(target, text)
                        print("renamed %s -> %s" % (p.name, target.name))
                else:
                    problems.append("%s: %s" % (p.name, "same number as " + ", ".join(
                        q.name for q in paths if q != p) if len(paths) > 1 else "name is not " + canonical(s, n)))
    files = entry_files()
    for s, n, p in files:
        text = read(p)
        if header_line(text, s, n) is None:
            problems.append("%s: the first lines do not name %s%d" % (p.name, s, n))
        if PLACEHOLDER in text:
            problems.append("%s: still has the placeholder bullet" % p.name)
    # Against the base: a number already used there must hold the same entry.
    tree = base_tree(base)
    rebased = has_ref(base) and subprocess.run(
        ["git", "-C", str(ROOT), "merge-base", "--is-ancestor", base, "HEAD"]).returncode == 0
    if has_ref(base) and not rebased:
        notes.append("HEAD is not on top of %s yet: run `git rebase %s`, then check again" % (base, base))
    blobs = local_blobs([p for _, _, p in files if p.name in tree])
    allowed = set(a.allow_edit or [])
    for s, n, p in files:
        if p.name not in tree or blobs.get(p) == tree[p.name]:
            continue
        mine, theirs = read(p), blob_text(tree[p.name])
        if mine == theirs:
            continue
        if mine.split("\n", 1)[0] != theirs.split("\n", 1)[0]:
            if a.fix:
                write(p, theirs)
                move_entry(mine, s, n, numbers, changed_files)
            else:
                problems.append("%s: %s already holds another entry (%r); run check --fix" % (
                    p.name, base, theirs.split("\n", 1)[0][:80]))
            continue
        it = iter(mine.split("\n"))
        if all(line in it for line in theirs.split("\n")):
            notes.append("%s: adds text to an entry already on %s" % (p.name, base))
        elif "%s%d" % (s, n) in allowed or str(n) in allowed:
            notes.append("%s: edits an entry already on %s (allowed)" % (p.name, base))
        else:
            problems.append("%s: removes or changes text of an entry already on %s "
                            "(write a new entry, or pass --allow-edit %s%d)" % (p.name, base, s, n))
    if rebased:
        local_names = {p.name for _, _, p in files}
        for name in tree:
            if "/" not in name and NAME.match(name) and name not in local_names:
                problems.append("%s: exists on %s but was deleted here" % (name, base))
    # Generated indexes.
    if a.fix:
        for p in regenerate():
            print("regenerated", p.relative_to(ROOT).as_posix())
            if in_rebase():
                git("add", "--", p.relative_to(ROOT).as_posix())
    else:
        for p, _ in stale_indexes():
            problems.append("%s: index is stale; run check --fix" % p.relative_to(ROOT).as_posix())
    size = STATE.stat().st_size
    if size > 30 * 1024:
        notes.append("PROJECT_LOG.md is %d bytes; keep the state file under 30 KB" % size)
    for n_ in notes:
        print("note:", n_)
    for p in problems:
        print("FAIL:", p)
    if not problems:
        print("check passed: %d entry files, base %s" % (len(entry_files()), base if has_ref(base) else "(none)"))
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--base", default=BASE, help="remote branch to compare with (default origin/main)")
    common.add_argument("--no-fetch", action="store_true", help="do not run git fetch first")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new", parents=[common], help="create the next entry file")
    p.add_argument("title")
    p.add_argument("--author", default="Claude Code")
    p.add_argument("--request", default="", help="who asked, e.g. coordinator's task \"...\"")
    p.add_argument("--series", choices="FG", default="F")
    p.add_argument("--number", type=int, help="use this number (a reserved one)")
    p.add_argument("--date", help="YYYY-MM-DD, default today")
    p = sub.add_parser("check", parents=[common], help="check numbers and indexes before a push")
    p.add_argument("--fix", action="store_true", help="renumber colliding entries, regenerate indexes")
    p.add_argument("--allow-edit", action="append", metavar="N", help="allow changing entry N (e.g. F512)")
    sub.add_parser("index", parents=[common], help="regenerate log/INDEX.md and the PROJECT_LOG.md index table")
    a = ap.parse_args()
    os.chdir(ROOT)
    return {"new": cmd_new, "check": cmd_check, "index": cmd_index}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
