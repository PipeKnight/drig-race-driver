"""Self-test of the git hooks (tools/hooks/check_commit.py through .githooks/): real commits in a
scratch repository, one per rule, each expected to pass or be refused.

    py -I tools/hooks/test_hooks.py

Prints one line per case and a verdict; exit 1 if any case behaves unexpectedly. Python standard
library only; needs git and, for the PowerShell case, Windows.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def run(repo, *args, data=None):
    env = dict(os.environ, GRID_PYTHON=sys.executable.replace("\\", "/"))
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, input=data, env=env)


def main():
    tmp = Path(tempfile.mkdtemp(prefix="drig-hooks-"))
    repo = tmp / "repo"
    try:
        repo.mkdir()
        run(repo, "init", "-q")
        for k, v in (("user.name", "Hook Test"), ("user.email", "hooks@example.invalid"),
                     ("core.autocrlf", "false"), ("core.hooksPath", ".githooks"), ("commit.gpgsign", "false")):
            run(repo, "config", k, v)
        (repo / "tools" / "hooks").mkdir(parents=True)
        shutil.copy2(ROOT / "tools" / "hooks" / "check_commit.py", repo / "tools" / "hooks")
        shutil.copytree(ROOT / ".githooks", repo / ".githooks")
        (repo / "docs").mkdir()
        (repo / "docs" / "A.md").write_text("# A\n", encoding="utf-8")
        run(repo, "add", "-A")
        base = run(repo, "commit", "-q", "-m", "base")
        if base.returncode != 0:
            print("FAIL setup: base commit refused:\n" + (base.stdout + base.stderr).decode("utf-8", "replace"))
            return 1

        cases = [
            # (name, expect_pass, files {path: bytes}, message, force_add)
            ("clean text change", True, {"docs/B.md": b"See [A](A.md).\n"}, "Docs", False),
            ("broken Markdown link", False, {"docs/C.md": b"See [X](MISSING.md).\n"}, "Docs", False),
            ("link into local/ is skipped", True, {"docs/D.md": b"See [x](../local/run/x.txt).\n"}, "Docs", False),
            ("conflict marker", False, {"src.txt": b"a\n<<<<<<< HEAD\nb\n=======\nc\n>>>>>>> x\n"}, "Merge", False),
            ("original game file", False, {"data/car.pssg": b"PSSG"}, "Asset", False),
            ("binary executable", False, {"bin/grid.exe": b"MZ"}, "Exe", False),
            ("forced file under local/", False, {"local/notes.txt": b"x\n"}, "Local", True),
            ("file over 5 MiB", False, {"big.txt": b"x" * (5 * 1024 * 1024 + 1)}, "Big", False),
            ("CRLF in third_party", False, {"third_party/c/s.wgsl": b"#ifdef A\r\nx\r\n#endif\r\n"}, "Vendor", False),
            ("LF in third_party", True, {"third_party/c/t.wgsl": b"#ifdef A\nx\n#endif\n"}, "Vendor", False),
            ("binary with CR in third_party", True, {"third_party/c/i.png": b"\x89PNG\r\n\x1a\n\0"}, "Vendor", False),
            ("Python syntax error", False, {"tools/bad.py": b"def f(:\n"}, "Py", False),
            ("valid Python", True, {"tools/good.py": b"print(1)\n"}, "Py", False),
            ("AI co-author trailer", False, {"docs/E.md": b"e\n"}, "Work\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", False),
            ("AI generated-with line", False, {"docs/F.md": b"f\n"}, "Work\n\nGenerated with Claude Code\n", False),
            ("racing AI wording passes", True, {"docs/G.md": b"g\n"}, "AI opponents: braking generated by the line model\n", False),
        ]
        if os.name == "nt":
            cases.append(("PowerShell syntax error", False, {"tools/bad.ps1": b"function f( {\n"}, "Ps", False))
            cases.append(("valid PowerShell", True, {"tools/good.ps1": b"Write-Output 1\n"}, "Ps", False))

        failures = 0
        for name, expect_pass, files, message, force in cases:
            for path, data in files.items():
                f = repo / path
                f.parent.mkdir(parents=True, exist_ok=True)
                f.write_bytes(data)
                run(repo, "add", *(["-f"] if force else []), "--", path)
            r = run(repo, "commit", "-q", "-F", "-", data=message.encode("utf-8"))
            passed = r.returncode == 0
            ok = passed == expect_pass
            failures += not ok
            print("%s %-32s %s" % ("ok  " if ok else "FAIL", name, "committed" if passed else "refused"))
            if not ok:
                print("     " + (r.stdout + r.stderr).decode("utf-8", "replace").strip().replace("\n", "\n     "))
            if not passed:
                run(repo, "reset", "-q", "--hard", "HEAD")
                run(repo, "clean", "-qfdx")
        print("hooks self-test: %s, %d cases, %d unexpected" % ("PASS" if not failures else "FAIL", len(cases), failures))
        return 1 if failures else 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
