//! Table emulation of the SSE approximate reciprocal (RCPPS) and reciprocal square root
//! (RSQRTPS), so the reference arithmetic also runs on CPUs without SSE (ARM: Android, Apple
//! Silicon). See docs/PLATFORMS_AND_INPUT_RESEARCH.md, "Approximate SSE arithmetic".
//!
//! The instructions are approximations whose exact bits are vendor specific. These tables were
//! measured on the owner's validation CPU (12th Gen Intel Core i7-12700, family 6 model 151)
//! with the default MXCSR. There RCPPS depends only on the top 11 mantissa bits and RSQRTPS on
//! the exponent parity and the top 10 mantissa bits; both return 12 significant bits. The
//! emulation below matched both instructions on all 2^32 inputs (zero mismatches), including
//! zeros, denormals (read as zero), infinities and NaNs.
//!
//! Each entry is the instruction's output for an input with exponent 127 (RCPPS; index = top 11
//! mantissa bits) or exponent 127/128 (RSQRTPS; index = (exponent - 127) * 1024 + top 10
//! mantissa bits). Other exponents only move the result exponent.

/// RCPPS lane result as measured on the validation CPU.
pub fn rcp(value: f32) -> f32 {
    let x = value.to_bits();
    let (sign, exponent, mantissa) = (x & 0x8000_0000, (x >> 23) & 0xff, x & 0x7f_ffff);
    if exponent == 0xff {
        // NaN is quieted; reciprocal of infinity is a signed zero.
        return f32::from_bits(if mantissa != 0 { x | 0x40_0000 } else { sign });
    }
    if exponent == 0 {
        // Zero and denormal inputs read as zero: signed infinity.
        return f32::from_bits(sign | 0x7f80_0000);
    }
    let base = RCP_BASE[(mantissa >> 12) as usize];
    let result = ((base >> 23) & 0xff) as i32 + 127 - exponent as i32;
    f32::from_bits(if result <= 0 {
        sign
    } else if result >= 255 {
        sign | 0x7f80_0000
    } else {
        sign | ((result as u32) << 23) | (base & 0x7f_ffff)
    })
}

/// RSQRTPS lane result as measured on the validation CPU.
pub fn rsqrt(value: f32) -> f32 {
    let x = value.to_bits();
    let (sign, exponent, mantissa) = (x & 0x8000_0000, (x >> 23) & 0xff, x & 0x7f_ffff);
    f32::from_bits(if exponent == 0xff {
        if mantissa != 0 {
            x | 0x40_0000
        } else if sign != 0 {
            0xffc0_0000
        } else {
            0
        }
    } else if exponent == 0 {
        sign | 0x7f80_0000
    } else if sign != 0 {
        0xffc0_0000
    } else {
        let high = (exponent + 1) & 1;
        let base = RSQRT_BASE[((high << 10) | (mantissa >> 13)) as usize];
        let result = ((base >> 23) & 0xff) as i32 - (exponent as i32 - (127 + high as i32)) / 2;
        ((result as u32) << 23) | (base & 0x7f_ffff)
    })
}

